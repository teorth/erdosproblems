#!/usr/bin/env python3
"""
Derives the combined `status` field of data/problems.yaml from the two primitive
fields `informal_status` and `formal_status`.

`status` is NOT meant to be edited by hand: it is regenerated by CI on every
push to `main`.  Contributors edit

  * `informal_status` - the human/mathematical status of the problem, and
  * `formal_status`   - whether a *solution* has been formalized, and in which
                        proof assistant ("unformalized" if none),

and `status.state` is then `informal_status.state`, with " (<system>)" appended
when `formal_status.state` is anything other than "unformalized".

Entries that predate this split (i.e. that carry only a combined `status`) are
backfilled by splitting that combined value, so the script is safe to run on
partially migrated data and is idempotent.

Usage:
    python scripts/derive_status.py           # rewrite data/problems.yaml in place
    python scripts/derive_status.py --check   # report staleness, exit 1 if any
"""

import argparse
import re
import sys
from pathlib import Path

from ruamel.yaml import YAML
from ruamel.yaml.comments import CommentedMap
from ruamel.yaml.scalarstring import DoubleQuotedScalarString as DQ

ROOT = Path(__file__).resolve().parents[1]
DATA_PATH = ROOT / "data" / "problems.yaml"

#: Value of `formal_status.state` meaning "no formalized solution is known".
UNFORMALIZED = "unformalized"

#: Permitted values of `informal_status.state`.  Kept in sync with
#: schema/problems.schema.json and the field notes in CONTRIBUTING.md.
INFORMAL_STATES = [
    "open",
    "proved",
    "disproved",
    "solved",
    "falsifiable",
    "verifiable",
    "decidable",
    "not provable",
    "not disprovable",
    "independent",
]

#: Permitted values of `formal_status.state`.
FORMAL_STATES = [UNFORMALIZED, "Lean"]

_SUFFIX_RE = re.compile(r"^(?P<informal>.*?)\s*\((?P<formal>[^()]+)\)$")


# --- Pure helpers (also imported by validate.py and generate_readme.py) ---

def split_legacy_status(state):
    """Split a combined status such as "proved (Lean)" into its two primitives.

    Returns an ``(informal_state, formal_state)`` pair; a status with no
    parenthesised suffix yields ``(state, "unformalized")``.
    """
    state = (state or "").strip()
    m = _SUFFIX_RE.match(state)
    if m:
        return m.group("informal").strip(), m.group("formal").strip()
    return state, UNFORMALIZED


def derive_state(informal_state, formal_state):
    """Combine the two primitive states into the derived `status.state`."""
    informal_state = (informal_state or "").strip()
    formal_state = (formal_state or UNFORMALIZED).strip()
    if not formal_state or formal_state == UNFORMALIZED:
        return informal_state
    return f"{informal_state} ({formal_state})"


def derive_last_update(informal_last_update, formal_last_update):
    """The later of the two primitive dates (ISO dates sort lexicographically)."""
    dates = [d for d in (informal_last_update, formal_last_update) if d]
    return max(dates) if dates else None


def expected_status(problem):
    """The `status` mapping that `problem` should have, as a plain dict.

    Returns an empty dict when the problem has neither primitive field, i.e.
    when there is nothing to derive from (such an entry needs backfilling).
    """
    informal = problem.get("informal_status") or {}
    formal = problem.get("formal_status") or {}
    if not informal and not formal:
        return {}

    out = {}
    state = derive_state(informal.get("state"), formal.get("state"))
    if state:
        out["state"] = state
    last_update = derive_last_update(
        informal.get("last_update"), formal.get("last_update")
    )
    if last_update:
        out["last_update"] = str(last_update)
    note = informal.get("note")
    if note:
        out["note"] = str(note)
    return out


def primitive_states(problem):
    """Return ``(informal_state, formal_state)`` for a problem.

    Falls back to splitting the combined `status` for entries that have not
    been migrated yet, so readers work on either representation.
    """
    informal = (problem.get("informal_status") or {}).get("state")
    formal = (problem.get("formal_status") or {}).get("state")
    if informal is None or formal is None:
        legacy_informal, legacy_formal = split_legacy_status(
            (problem.get("status") or {}).get("state", "")
        )
        if informal is None:
            informal = legacy_informal
        if formal is None:
            formal = legacy_formal
    return informal or "", formal or UNFORMALIZED


# --- Mutation ---

def _insert_before(problem, anchor, key, value):
    """Insert ``key`` into the ``CommentedMap`` just before ``anchor``."""
    keys = list(problem.keys())
    pos = keys.index(anchor) if anchor in keys else len(keys)
    problem.insert(pos, key, value)


def backfill(problem):
    """Populate missing primitives by splitting the combined `status`.

    Returns True if the problem was modified.
    """
    if "informal_status" in problem and "formal_status" in problem:
        return False

    legacy = problem.get("status") or {}
    legacy_last_update = legacy.get("last_update")
    legacy_note = legacy.get("note")
    informal_state, formal_state = split_legacy_status(legacy.get("state", ""))

    changed = False

    if "informal_status" not in problem:
        entry = CommentedMap()
        if informal_state:
            entry["state"] = DQ(informal_state)
        if legacy_last_update:
            entry["last_update"] = DQ(str(legacy_last_update))
        if legacy_note:
            entry["note"] = DQ(str(legacy_note))
        _insert_before(problem, "status", "informal_status", entry)
        changed = True

    if "formal_status" not in problem:
        entry = CommentedMap()
        entry["state"] = DQ(formal_state)
        # A date is only meaningful once something has actually been formalized.
        if formal_state != UNFORMALIZED and legacy_last_update:
            entry["last_update"] = DQ(str(legacy_last_update))
        _insert_before(problem, "status", "formal_status", entry)
        changed = True

    return changed


def sync_status(problem):
    """Rewrite `status` from the primitives.  Returns True if modified."""
    want = expected_status(problem)
    if not want:
        return False

    current = problem.get("status")
    if current is None:
        entry = CommentedMap()
        for key, value in want.items():
            entry[key] = DQ(value)
        keys = list(problem.keys())
        if "formal_status" in keys:
            problem.insert(keys.index("formal_status") + 1, "status", entry)
        else:
            problem["status"] = entry
        return True

    changed = False
    for key, value in want.items():
        if current.get(key) != value:
            current[key] = DQ(value)
            changed = True
    for key in [k for k in current.keys() if k not in want]:
        del current[key]
        changed = True
    return changed


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--check",
        action="store_true",
        help="report what would change and exit 1 if anything is stale, without writing",
    )
    args = parser.parse_args()

    yaml = YAML()
    yaml.preserve_quotes = True
    yaml.indent(mapping=2, sequence=2, offset=0)

    try:
        with DATA_PATH.open("r", encoding="utf-8") as f:
            data = yaml.load(f)
    except FileNotFoundError:
        print(f"Error: data file not found at {DATA_PATH}", file=sys.stderr)
        return 1

    backfilled = []
    resynced = []
    for problem in data:
        number = problem.get("number")
        was_backfilled = backfill(problem)
        status_changed = sync_status(problem)
        if was_backfilled:
            backfilled.append(number)
        elif status_changed:
            resynced.append(number)

    if args.check:
        for number in backfilled:
            print(f"{DATA_PATH}: problem {number}: missing informal_status/formal_status")
        for number in resynced:
            print(f"{DATA_PATH}: problem {number}: 'status' is out of date")
        if backfilled or resynced:
            print(f"\n❌ {len(backfilled) + len(resynced)} entries are stale; run scripts/derive_status.py.")
            return 1
        print("✅ Derived statuses are up-to-date.")
        return 0

    if backfilled or resynced:
        with DATA_PATH.open("w", encoding="utf-8") as f:
            yaml.dump(data, f)
        print(
            f"✅ Backfilled {len(backfilled)} entries and refreshed "
            f"{len(resynced)} derived statuses in {DATA_PATH.name}."
        )
    else:
        print("🧘 No changes needed. Derived statuses are already up-to-date.")
    return 0


if __name__ == "__main__":
    sys.exit(main())